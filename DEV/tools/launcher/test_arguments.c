/* Independent single-argument CRT-style decoder for the string generated by arg. */
static void roundtrip(PCWSTR input){
 WCHAR output[1024];int n=0,q=0;PCWSTR p;
 used=0;line[0]=0;arg(input);p=line;
 while(*p){
  int slash=0;
  if(!q&&(*p==' '||*p=='\t'))break;
  while(*p=='\\'){slash++;p++;}
  if(*p=='"'){
   for(int j=0;j<slash/2;j++)output[n++]='\\';
   if(slash%2)output[n++]='"';else q=!q;
   p++;
  }else{
   for(int j=0;j<slash;j++)output[n++]='\\';
   if(*p)output[n++]=*p++;
  }
  if(n>=1020){fprintf(stderr,"decoder overflow\n");exit(1);}
 }
 output[n]=0;
 if(q||!exact16(output,input)){fprintf(stderr,"roundtrip failed\n");exit(1);}
}
